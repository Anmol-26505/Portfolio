// Synthesized cybernetic audio utility using the Web Audio API (Zero external audio assets needed)
let audioCtx = null;
let isSoundEnabled = false;

const getAudioContext = () => {
  if (typeof window === "undefined") return null;
  if (!audioCtx) {
    const AudioContext = window.AudioContext || window.webkitAudioContext;
    if (AudioContext) {
      audioCtx = new AudioContext();
    }
  }
  if (audioCtx && audioCtx.state === "suspended") {
    audioCtx.resume();
  }
  return audioCtx;
};

export const toggleSound = () => {
  isSoundEnabled = !isSoundEnabled;
  if (isSoundEnabled) {
    getAudioContext();
    playChirp();
  }
  return isSoundEnabled;
};

export const getSoundStatus = () => isSoundEnabled;

export const setSoundStatus = (enabled) => {
  isSoundEnabled = enabled;
  if (enabled) {
    getAudioContext();
  }
};

// Subtle click / tick for buttons and links
export const playClick = () => {
  if (!isSoundEnabled) return;
  try {
    const ctx = getAudioContext();
    if (!ctx) return;
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = "sine";
    osc.frequency.setValueAtTime(800, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(300, ctx.currentTime + 0.04);

    gain.gain.setValueAtTime(0.08, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.04);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start();
    osc.stop(ctx.currentTime + 0.04);
  } catch {
    // Ignore audio errors
  }
};

// Futuristic soft chirp when opening modals or executing commands
